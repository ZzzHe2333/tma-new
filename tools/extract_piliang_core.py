"""Extract the supplied V14 reader and V233 calculations without loading Tk."""
import ast
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "power/piliang_tma_v14.py"


def extract():
    source = SOURCE.read_text(encoding="utf-8-sig")
    tree = ast.parse(source)
    nodes = {n.name: n for n in tree.body if isinstance(n, (ast.FunctionDef, ast.ClassDef))}
    constants = {n.targets[0].id: n for n in tree.body
                 if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name)}
    wanted = {"load_text_prefer_tajm", "parse_lines", "extract_xy_from_file",
              "detect_T2_T1_super_gradient", "build_curve_cache", "interpolate_curve_height",
              "format_height_um", "format_plot_temp_c"}
    while True:
        before = set(wanted)
        for name in before:
            wanted.update(n.id for n in ast.walk(nodes[name]) if isinstance(n, ast.Name) and n.id in nodes)
        if wanted == before:
            break
    used_constants = {n.id for name in wanted for n in ast.walk(nodes[name])
                      if isinstance(n, ast.Name) and n.id in constants}
    selected = sorted([nodes[n] for n in wanted] + [constants[n] for n in used_constants], key=lambda n: n.lineno)
    lines = source.splitlines(keepends=True)
    fragments = []
    for node in selected:
        start = min([node.lineno] + [d.lineno for d in getattr(node, "decorator_list", [])])
        fragments.append("".join(lines[start - 1:node.end_lineno]).rstrip())
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    prelude = ('"""Verbatim reader and V233 numerical dependency closure from the supplied V14.\n'
               'Generated by tools/extract_piliang_core.py. No Tk, splash, GUI or source writes.\n"""\n'
               'from __future__ import annotations\n'
               'import os, re, math, logging, datetime, struct\n'
               'from dataclasses import dataclass\n'
               'from typing import Any, Dict, List, Optional, Tuple\nimport numpy as np\n'
               f'SOURCE_FILE = {SOURCE.name!r}\nSOURCE_SHA256 = {digest!r}\nALGORITHM_VERSION = "V233"\n\n')
    (ROOT / "tma_app/piliang_core.py").write_text(prelude + "\n\n\n".join(fragments) + "\n", encoding="utf-8")
    out = ROOT / "artifacts/batch-v233-verification"
    out.mkdir(parents=True, exist_ok=True)
    (out / "algorithm-provenance.json").write_text(json.dumps({"source": str(SOURCE), "sha256": digest,
        "definitions": [{"name": getattr(n, "name", None) or n.targets[0].id, "line": n.lineno, "end": n.end_lineno}
                        for n in selected], "verbatim": True}, indent=2), encoding="utf-8")
    print(f"Extracted {len(wanted)} definitions; source SHA256 {digest}")


if __name__ == "__main__":
    extract()
