"""Produce a portable single Python file, with NumPy as its only core dependency."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build(destination=None):
    destination = Path(destination) if destination else ROOT / "dist/T1-T2-H/extract_t1_t2_h.py"
    pieces = []
    for name in ("tma_app/reader.py", "tma_app/legacy_t1_t2_h.py", "tma_app/t1_t2_h.py", "extract_t1_t2_h.py"):
        source = (ROOT / name).read_text(encoding="utf-8")
        lines = [line for line in source.splitlines() if not line.startswith(("from __future__ import", "from . import legacy_t1_t2_h", "from .reader import", "from tma_app.t1_t2_h import"))]
        source = "\n".join(lines)
        if name == "tma_app/t1_t2_h.py": source = source.replace("original.", "")
        pieces.append(f"\n# ---- {name}: copied from the project ----\n{source}\n")
    combined = ('#!/usr/bin/env python\n# -*- coding: utf-8 -*-\n'
                '"""Standalone T1/T2/H extraction. Requires NumPy; optional plots require Matplotlib.\n'
                'Generated by tools/build_t1_t2_h_standalone.py; no Qt/Tkinter or project imports.\n"""\n'
                'from __future__ import annotations\n') + "\n".join(pieces)
    compile(combined, str(destination), "exec")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(combined, encoding="utf-8")
    destination.with_name("README.txt").write_text('''T1 / T2 / H 独立提取脚本

只需要 Python 3.11+ 和 NumPy：python -m pip install numpy
不需要本项目目录、Qt、Tkinter 或原版 TA 程序。

python extract_t1_t2_h.py "D:\\data\\sample.001"
python extract_t1_t2_h.py "D:\\data\\sample.001" --json result.json --csv result.csv --quiet
python extract_t1_t2_h.py "D:\\data" --recursive --csv results.csv --quiet

默认 --algorithm super；也支持 --algorithm robust。
可选 --plot-dir plots：按原脚本十字、两温度、水平基线、高度箭头绘图，需安装 matplotlib。
升降温循环需明确 --sample-start 0 --sample-stop 1000（0 起算，起点含、终点不含）。

算法逐函数原样提取自用户提供的 power/tma_super_max_v219.py，包含其内部 v233 修订。
T1/T2 单位 °C；H1/H2/H 单位 µm；H=H2-H1；area 为原曲线 T1~T2 积分，µm·°C。
沿用原算法：温度排序、重复温度取平均、端点插值；没有温度 warp、mg 修正或单调修复。
原始文件只读。识别失败会写入 errors 并返回非零退出码，CSV 也记录失败文件。
''', encoding="utf-8")
    print(destination)
    return destination


if __name__ == "__main__": build()
