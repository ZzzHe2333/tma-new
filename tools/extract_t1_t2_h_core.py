"""Copy only the user's numerical dependency closure; never execute the GUI source."""
from pathlib import Path
import ast
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "power/tma_super_max_v219.py"


def extract():
    source = SOURCE.read_text(encoding="utf-8-sig")
    tree = ast.parse(source)
    nodes = {node.name: node for node in tree.body if isinstance(node, (ast.FunctionDef, ast.ClassDef))}
    wanted = {"_compute_t1_t2_h_integral_details", "format_height_um", "format_plot_temp_c"}
    while True:
        previous = wanted.copy()
        for name in previous:
            wanted.update({node.id for node in ast.walk(nodes[name]) if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Load)} & nodes.keys())
        if wanted == previous: break
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    prelude = ('"""Numerical functions copied verbatim from the user-provided v219 file.\n'
               'Generated by tools/extract_t1_t2_h_core.py; edit the adapter, not this file.\n'
               'The original algorithm sorts temperature and averages duplicate temperatures.\n'
               'No GUI, output-file, warp, mass scaling or spreadsheet code is imported.\n"""\n'
               'from __future__ import annotations\nimport math\nimport numpy as np\n'
               'from typing import Any, Dict, List, Optional, Tuple\n'
               f'SOURCE_FILE = {SOURCE.name!r}\nSOURCE_SHA256 = {digest!r}\n'
               'START_TEMP_FOR_T1 = 60.0\n\n')
    selected = sorted((nodes[name] for name in wanted), key=lambda node: node.lineno)
    body = "\n\n\n".join(ast.get_source_segment(source, node) for node in selected)
    (ROOT / "tma_app/legacy_t1_t2_h.py").write_text(prelude + body + "\n", encoding="utf-8")
    evidence = {"source": str(SOURCE), "sha256": digest, "constant": {"START_TEMP_FOR_T1": 60.0},
                "functions": [{"name": node.name, "line": node.lineno, "last_line": node.end_lineno} for node in selected],
                "unchanged_functions": True, "v208": "SyntaxError at line 20 in supplied file; not modified"}
    out = ROOT / "artifacts/point-verification"
    out.mkdir(parents=True, exist_ok=True)
    (out / "algorithm-provenance.json").write_text(json.dumps(evidence, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Extracted {len(selected)} numerical definitions from {SOURCE.name}; SHA256 {digest}")


if __name__ == "__main__": extract()
