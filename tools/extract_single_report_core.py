"""Retain the supplied report algorithms/layouts without importing either Tk UI."""
import ast
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def extract(source_name, target_name, roots):
    path = ROOT / "power" / source_name
    source = path.read_text(encoding="utf-8-sig")
    tree = ast.parse(source)
    definitions = {n.name: n for n in tree.body if isinstance(n, (ast.FunctionDef, ast.ClassDef))}
    constants = {}
    for node in tree.body:
        if isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            for target in targets:
                if isinstance(target, ast.Name):
                    constants[target.id] = node
                elif isinstance(target, ast.Tuple):
                    for item in target.elts:
                        if isinstance(item, ast.Name):
                            constants[item.id] = node
    selected = {name: definitions[name] for name in roots}
    while True:
        before = set(selected)
        for node in list(selected.values()):
            for n in ast.walk(node):
                if not isinstance(n, ast.Name) or n.id in selected or n.id == "UILogger":
                    continue
                if n.id in definitions:
                    selected[n.id] = definitions[n.id]
                elif n.id in constants:
                    selected[n.id] = constants[n.id]
        if before == set(selected):
            break
    lines = source.splitlines(keepends=True)
    nodes = sorted({id(n): n for n in selected.values()}.values(), key=lambda n: n.lineno)
    fragments = []
    for node in nodes:
        start = min([node.lineno] + [d.lineno for d in getattr(node, "decorator_list", [])])
        fragments.append("".join(lines[start-1:node.end_lineno]).rstrip())
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    prelude = ('"""Verbatim non-GUI dependency closure from the user supplied report script.\n'
               'Generated by tools/extract_single_report_core.py; no Tk, default UNC routes, or UI startup.\n"""\n'
               'from __future__ import annotations\n'
               'import os, re, json, math, struct, logging, datetime, secrets, string, tempfile\n'
               'from dataclasses import dataclass\nfrom typing import Any, Dict, List, Optional, Tuple\n'
               'import numpy as np\nimport fitz\nfrom PIL import Image, ImageDraw, ImageFont\n'
               'from matplotlib.figure import Figure\nfrom matplotlib.backends.backend_agg import FigureCanvasAgg\n'
               'from matplotlib.ticker import MultipleLocator, NullFormatter, FixedLocator\n'
               f'SOURCE_FILE = {source_name!r}\nSOURCE_SHA256 = {digest!r}\n\n')
    (ROOT / "tma_app" / target_name).write_text(prelude + "\n\n\n".join(fragments) + "\n", encoding="utf-8")
    return {"source": str(path), "sha256": digest, "module": target_name, "verbatim": True,
            "definitions": [{"name": name, "line": node.lineno, "end": node.end_lineno} for name, node in selected.items()]}


if __name__ == "__main__":
    roots = {"load_text_prefer_tajm", "parse_lines", "extract_xy_from_file", "detect_T2_T1_precise",
             "detect_T2_T1_super_gradient", "build_curve_cache", "interpolate_curve_height",
             "format_height_um", "format_plot_temp_c", "calc_tma_from_m_h", "generate_tma_tif",
             "_extract_tma_internal_datetime", "build_final_pdf_internal", "_p9m_parse_records", "_p9m_generate_pdf"}
    reports = [extract("one_BG_neibuban.py", "report_internal_core.py", roots),
               extract("one_BG_claude_v6.py", "report_template_core.py", {"PDFTemplateEditor"})]
    out = ROOT / "artifacts/single-report-verification"
    out.mkdir(parents=True, exist_ok=True)
    (out / "provenance.json").write_text(json.dumps(reports, ensure_ascii=False, indent=2), encoding="utf-8")
    print("Extracted report cores", [len(r["definitions"]) for r in reports])
