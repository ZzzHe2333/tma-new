def format_height_um(v: float) -> str:
    """高度显示规则（μm，不含单位）：

    - |v| > 1000：保留到个位（无小数）
    - |v| <= 1000：保留 1 位小数
    """
    try:
        if v is None:return "NA"
        v = float(v)
        if not math.isfinite(v):return "NA"
        if abs(v) > 1000.0:return f"{v:.0f}"
        return f"{v:.1f}"
    except Exception:return "NA"


